#!/usr/bin/env python3
"""Generates src/emoji_table.rs from gemoji's db/emoji.json (stdlib only)."""
import json
import os
import urllib.request

URL = "https://raw.githubusercontent.com/github/gemoji/master/db/emoji.json"
OUT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "src", "emoji_table.rs")

HEADER = """// Generated by scripts/gen_emoji.py - do not edit.
// Data derived from gemoji (https://github.com/github/gemoji), MIT License,
// Copyright (c) 2022 GitHub, Inc. See THIRD_PARTY_NOTICES.md.

#[rustfmt::skip]
pub static EMOJI: &[(&str, &str)] = &[
"""


def lit(s):
    return json.dumps(s, ensure_ascii=False)


def main():
    with urllib.request.urlopen(URL, timeout=60) as r:
        data = json.load(r)
    table = {}
    for entry in data:
        for alias in entry.get("aliases", []):
            table.setdefault(alias, entry["emoji"])
    # Python sorts str by code point, which equals UTF-8 byte order.
    with open(OUT, "w", encoding="utf-8") as f:
        f.write(HEADER)
        for alias in sorted(table):
            f.write("    (%s, %s),\n" % (lit(alias), lit(table[alias])))
        f.write("];\n")
    print("wrote %d aliases" % len(table))


if __name__ == "__main__":
    main()
